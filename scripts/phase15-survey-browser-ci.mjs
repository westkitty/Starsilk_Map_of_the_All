/** Phase 15: non-canonical survey cells + authored region independence. */
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {existsSync,mkdirSync} from 'node:fs';
import {chromium} from 'playwright-core';
const uri='http://127.0.0.1:4173/Starsilk_Map_of_the_All/?atlasDiagnostics=1';
const binary=['/usr/bin/google-chrome-stable','/usr/bin/google-chrome','/usr/bin/chromium','/opt/google/chrome/chrome','/Applications/Google Chrome.app/Contents/MacOS/Google Chrome','/Applications/Brave Browser.app/Contents/MacOS/Brave Browser'].find(existsSync);
if(!binary)throw Error('Chromium required for Phase 15 browser proof');
mkdirSync('atlas-qa-evidence',{recursive:true});
const server=spawn(process.execPath,['./node_modules/vite/bin/vite.js','preview','--host','127.0.0.1','--port','4173','--strictPort'],{stdio:['ignore','pipe','pipe']});
let serverLog='';for(const out of [server.stdout,server.stderr])out.on('data',d=>serverLog+=String(d).slice(0,1000));
let browser;
const watchdog=setTimeout(()=>{console.error('PHASE15_BROWSER_TIMEOUT');server.kill('SIGTERM');process.exit(124);},210000);watchdog.unref();
async function ready(){for(let n=0;n<80;n++){if(server.exitCode!==null)throw Error('Preview terminated '+serverLog);try{if((await fetch(uri)).ok)return;}catch{}await new Promise(r=>setTimeout(r,250));}throw Error('Vite preview inaccessible: '+serverLog);}
const diag=page=>page.evaluate(()=>window.__atlasDiagnostics?.());
const wait=async(page,condition,args)=>page.waitForFunction(condition,args,{timeout:20000});
try{
  await ready();
  browser=await chromium.launch({executablePath:binary,headless:true,args:['--no-sandbox','--disable-setuid-sandbox','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
  const context=await browser.newContext({viewport:{width:1536,height:864},reducedMotion:'reduce'});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(uri,{waitUntil:'domcontentloaded',timeout:30000});
  await page.locator('.world-label').first().waitFor({timeout:30000});
  await wait(page,()=>window.__atlasDiagnostics?.().provisionalCells===7);
  let m=await diag(page);
  assert.equal(m.authoredSectors,0);
  assert.equal(m.viewKind,'all');
  assert.equal(m.epoch,'post');
  console.log('PHASE15_STAGE seeded-provisional-cells '+JSON.stringify({cells:m.provisionalCells,drawCalls:m.drawCalls}));
  await page.screenshot({path:'atlas-qa-evidence/phase15-survey-cells-desktop.png'});
  await page.locator('[data-drawer="nav"]').click();
  const toggle=page.locator('input[aria-label="Toggle Provisional sectors"]');
  await toggle.uncheck();
  await wait(page,()=>window.__atlasDiagnostics?.().provisionalCells===0);
  await wait(page,()=>{const raw=localStorage.getItem('starsilk.map-of-the-all.draft.v1');return raw&&JSON.parse(raw).layers.territories===false;});
  await toggle.check();
  await wait(page,()=>window.__atlasDiagnostics?.().provisionalCells===7);
  assert.equal((await page.evaluate(()=>JSON.parse(localStorage.getItem('starsilk.map-of-the-all.draft.v1')))).regions.length,0);
  console.log('PHASE15_STAGE reversible-layer-toggle');
  await page.locator('[data-drawer="regions"]').click();
  assert.equal(await page.locator('#strategyPanel').isVisible(),true);
  await page.locator('.world-label[data-atlas-id="perseus-confluence"]').click();
  await page.locator('.world-label[data-atlas-id="centauri-marches"]').click({modifiers:['Shift']});
  await page.locator('#strategyFromGroup').click();
  await wait(page,()=>window.__atlasDiagnostics?.().authoredSectors===1);
  assert.equal((await diag(page)).provisionalCells,7,'real draft and illustrative cells coexist');
  await page.locator('#strategyRegionName').fill('UNCLAIMED TEST SECTOR');
  await page.locator('#strategyRegionForm button[type="submit"]').click();
  await wait(page,()=>JSON.parse(localStorage.getItem('starsilk.map-of-the-all.draft.v1'))?.regions?.[0]?.name==='UNCLAIMED TEST SECTOR');
  await page.locator('#strategyClose').click();
  assert.equal(await page.locator('#strategyPanel').isVisible(),false);
  assert.equal((await diag(page)).authoredSectors,1,'authored Three.js polygon must remain after closing editor');
  console.log('PHASE15_STAGE authored-sector-independence');
  await page.locator('[data-drawer="nav"]').click();
  await page.locator('#undoBtn').click();
  await wait(page,()=>window.__atlasDiagnostics?.().authoredSectors===1);
  // First Undo reverts region rename; second undoes the actual region creation.
  await page.locator('#undoBtn').click();
  await wait(page,()=>window.__atlasDiagnostics?.().authoredSectors===0);
  await page.locator('#redoBtn').click();
  await wait(page,()=>window.__atlasDiagnostics?.().authoredSectors===1);
  assert.equal((await diag(page)).provisionalCells,7);
  console.log('PHASE15_STAGE undo-redo-isolated');
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('.world-label').first().waitFor({timeout:30000});
  await wait(page,()=>window.__atlasDiagnostics?.().authoredSectors===1);
  await page.locator('[data-drawer="eras"]').click();
  await page.locator('.era-btn').filter({hasText:'BLOOD ECLIPSE'}).click();
  await wait(page,()=>window.__atlasDiagnostics?.().epoch==='war');
  await wait(page,()=>window.__atlasDiagnostics?.().authoredSectors===0);
  assert.equal((await diag(page)).provisionalCells,7);
  await page.locator('.era-btn').filter({hasText:'POST-SIEGE'}).click();
  await wait(page,()=>window.__atlasDiagnostics?.().epoch==='post');
  await wait(page,()=>window.__atlasDiagnostics?.().authoredSectors===1);
  const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('starsilk.map-of-the-all.draft.v1')));
  assert.equal(stored.version,1);
  assert.equal(stored.regions.length,1);
  assert.equal(stored.regions[0].status,'draft');
  assert.equal(stored.regions[0].name,'NEW SURVEY SECTOR');
  assert.equal(stored.timeline.snapshots.war.regions.length,0);
  console.log('PHASE15_STAGE reload-and-three-era-separation');
  await context.close();
  const touch=await browser.newContext({viewport:{width:412,height:915},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  const phone=await touch.newPage();phone.on('pageerror',e=>errors.push('TOUCH '+e.message));
  await phone.goto(uri,{waitUntil:'domcontentloaded'});
  await phone.locator('.world-label').first().waitFor({timeout:30000});
  await wait(phone,()=>window.__atlasDiagnostics?.().provisionalCells===7);
  const viewport=await phone.evaluate(()=>({screen:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(viewport.scroll<=viewport.screen,'No horizontal scrolling on touch emulation');
  await phone.screenshot({path:'atlas-qa-evidence/phase15-survey-cells-mobile.png'});
  assert.deepEqual(errors,[],'No runtime exceptions');
  console.log('PHASE15_BROWSER_PASS '+JSON.stringify({cells:7,sourceStatus:'provisional-only',authored:true,undoRedo:true,reload:true,eraIsolation:true,mobile:viewport,physicalDevice:false}));
  await touch.close();
}catch(error){console.error('PHASE15_BROWSER_FAIL',error.stack||error);process.exitCode=1;}
finally{await browser?.close();server.kill('SIGTERM');clearTimeout(watchdog);}
process.exit(process.exitCode||0);
